/**
 * npm run publish-kit -- <video-id>
 *
 * Prepares everything for a manual YouTube upload:
 *   videos/<id>/publish.md    chapters (always regenerated between markers), plus title,
 *                             description, tags and pinned comment sections for Claude to write
 *   out/<id>/thumbnail.png    1280×720 thumbnail rendered from spec.thumbnail
 */
import fs from "node:fs";
import path from "node:path";
import { compile } from "../src/spec/compile";
import { cli, fmtTime, loadRawSpec, loadTiming, paths, rel, remotionBrowserArgs, requireId, run } from "./lib/common";
import { sync } from "./sync";

const { positionals } = cli({});
const id = requireId(positionals);
const P = paths(id);
const c = compile(loadRawSpec(id) as never, loadTiming(id));
const chapters = c.chapters.map((ch) => `${fmtTime(ch.frame / c.fps)} ${ch.title}`).join("\n");
const block = `<!-- chapters:start (generated by npm run publish-kit; do not edit inside) -->\n${chapters || "0:00 Intro"}\n<!-- chapters:end -->`;
let md = fs.existsSync(P.publish) ? fs.readFileSync(P.publish, "utf8") : "";
if (md.includes("<!-- chapters:start")) md = md.replace(/<!-- chapters:start[\s\S]*?<!-- chapters:end -->/, block);
else
  md = `# Publish kit: ${c.spec.title}

Runtime ${fmtTime(c.durationInFrames / c.fps)}${c.draft ? " (estimated — voice the narration before publishing)" : ""}.

## Title options
<!-- 3 options, ≤ 60 characters, promise + curiosity, no clickbait the video does not pay off -->

## Description
<!-- 2–3 lines on what the viewer learns, then chapters, then sources -->

### Chapters
${block}

### Sources
<!-- copy from brief.md -->

## Tags
<!-- 8–12 tags -->

## Pinned comment
<!-- a question that invites answers -->

## Upload checklist
- [ ] Watched the full render once at phone size
- [ ] Title and thumbnail tell the same story
- [ ] Chapters pasted into the description (first one at 0:00)
- [ ] "Altered or synthetic content" disclosure considered (AI voice, no realistic people: usually not required)
- [ ] End screen and cards added in YouTube Studio
`;
fs.writeFileSync(P.publish, md);
console.log(`chapters written to ${rel(P.publish)}`);

if (c.spec.thumbnail) {
  sync(true);
  fs.mkdirSync(P.out, { recursive: true });
  run("npx", ["remotion", "still", "src/index.ts", `thumb-${id}`, path.join(P.out, "thumbnail.png"), ...remotionBrowserArgs()]);
  console.log(`thumbnail: ${rel(path.join(P.out, "thumbnail.png"))}`);
}
