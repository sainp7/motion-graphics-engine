/**
 * npm run sync
 *
 * Regenerates:
 *   src/registry.generated.ts      every video in videos/ (a Remotion composition each) and its
 *                                  custom scenes in videos/<id>/scenes/ (.tsx React, .js/.ts seekable script)
 *   src/channels.generated.ts      every channels/<id>/channel.json and studio.json's default channel
 *   src/styles.generated.ts        every style in src/styles/<id>/ (index.tsx), for the renderer
 *   src/style-tokens.generated.ts  the same styles' tokens only (pure data), for Node scripts
 *   schema/*.schema.json           editor validation for spec.json and channel.json (editor validation and autocomplete for spec.json).
 * Called automatically by studio, sheet and render.
 */
import fs from "node:fs";
import path from "node:path";
import { z } from "zod";
import { VideoSpec } from "../src/spec/schema";
import { ChannelSpec } from "../src/spec/channel-schema";
import { ROOT, listVideos, paths } from "./lib/paths";

const writeIfChanged = (file: string, text: string) => {
  if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== text) fs.writeFileSync(file, text);
};

export const sync = (quiet = false) => {
  const ids = listVideos();
  const lines: string[] = [
    "// AUTO-GENERATED by scripts/sync.ts — do not edit by hand. Run `npm run sync`.",
    'import type { VideoSpecInput } from "./spec/schema";',
    'import type { TimingFile } from "./spec/timing";',
    'import type { ComponentType } from "react";',
    'import type { CustomSceneProps } from "./custom/kit";',
  ];
  const entries: string[] = [];
  const customs: string[] = [];
  ids.forEach((id, i) => {
    lines.push(`import spec${i} from "../videos/${id}/spec.json";`);
    const hasTiming = fs.existsSync(paths(id).timing);
    if (hasTiming) lines.push(`import timing${i} from "../public/videos/${id}/timing.json";`);
    entries.push(
      `  { id: ${JSON.stringify(id)}, spec: spec${i} as unknown as VideoSpecInput, timing: ${hasTiming ? `timing${i} as unknown as TimingFile` : "null"} },`,
    );
    const sceneDir = path.join(ROOT, "videos", id, "scenes");
    const files = fs.existsSync(sceneDir) ? fs.readdirSync(sceneDir).filter((f) => /^[A-Z][A-Za-z0-9]*\.(tsx|ts|js)$/.test(f)).sort() : [];
    if (files.length) {
      const entriesForVideo: string[] = [];
      for (const f of files) {
        const n = f.replace(/\.(tsx|ts|js)$/, "");
        const script = !f.endsWith(".tsx");
        lines.push(`import custom${i}_${n} from "../videos/${id}/scenes/${f.endsWith(".js") ? f : n}";`);
        entriesForVideo.push(`${n}: ${script ? `scriptScene(custom${i}_${n})` : `custom${i}_${n}`}`);
      }
      customs.push(`  ${JSON.stringify(id)}: { ${entriesForVideo.join(", ")} },`);
    }
  });
  if (customs.some((c) => c.includes("scriptScene("))) lines.splice(5, 0, 'import { scriptScene } from "./custom/script";');
  lines.push("", "export const REGISTRY: { id: string; spec: VideoSpecInput; timing: TimingFile | null }[] = [", ...entries, "];", "");
  lines.push(
    "/** Custom scenes per video: videos/<id>/scenes/<Name>.tsx (default export). */",
    "// eslint-disable-next-line @typescript-eslint/no-explicit-any",
    "export const CUSTOM_SCENES: Record<string, Record<string, ComponentType<CustomSceneProps<any>>>> = {",
    ...customs,
    "};",
    "",
  );
  writeIfChanged(path.join(ROOT, "src", "registry.generated.ts"), lines.join("\n"));

  // ---- channels
  const studio = fs.existsSync(path.join(ROOT, "studio.json")) ? JSON.parse(fs.readFileSync(path.join(ROOT, "studio.json"), "utf8")) : {};
  const chDir = path.join(ROOT, "channels");
  const channels = fs.existsSync(chDir) ? fs.readdirSync(chDir).filter((d) => fs.existsSync(path.join(chDir, d, "channel.json"))).sort() : [];
  const ch = [
    "// AUTO-GENERATED by scripts/sync.ts — do not edit by hand. Run `npm run sync`.",
    ...channels.map((c, i) => `import channel${i} from "../channels/${c}/channel.json";`),
    "",
    `export const CHANNELS: Record<string, unknown> = { ${channels.map((c, i) => `${JSON.stringify(c)}: channel${i}`).join(", ")} };`,
    `export const DEFAULT_CHANNEL: string = ${JSON.stringify(studio.defaultChannel ?? channels[0] ?? "")};`,
    "",
  ].join("\n");
  writeIfChanged(path.join(ROOT, "src", "channels.generated.ts"), ch);

  // ---- styles
  const stDir = path.join(ROOT, "src", "styles");
  const styles = fs.readdirSync(stDir).filter((d) => fs.existsSync(path.join(stDir, d, "index.tsx")) && fs.existsSync(path.join(stDir, d, "tokens.ts"))).sort();
  const ident = (st: string) => `style_${st.replace(/[^a-zA-Z0-9]/g, "_")}`;
  writeIfChanged(
    path.join(ROOT, "src", "styles.generated.ts"),
    [
      "// AUTO-GENERATED by scripts/sync.ts — do not edit by hand. Run `npm run sync`.",
      'import type { StyleDef } from "./styles/types";',
      ...styles.map((st) => `import ${ident(st)} from "./styles/${st}";`),
      "",
      `export const STYLES: Record<string, StyleDef> = { ${styles.map((st) => `${JSON.stringify(st)}: ${ident(st)}`).join(", ")} };`,
      "",
    ].join("\n"),
  );
  writeIfChanged(
    path.join(ROOT, "src", "style-tokens.generated.ts"),
    [
      "// AUTO-GENERATED by scripts/sync.ts — do not edit by hand. Run `npm run sync`.",
      'import type { StyleTokens } from "./design/style-tokens";',
      ...styles.map((st) => `import ${ident(st)} from "./styles/${st}/tokens";`),
      "",
      `export const STYLE_TOKENS: Record<string, StyleTokens> = { ${styles.map((st) => `${JSON.stringify(st)}: ${ident(st)}`).join(", ")} };`,
      "",
    ].join("\n"),
  );

  const chSchema = z.toJSONSchema(ChannelSpec, { io: "input", unrepresentable: "any" });
  fs.mkdirSync(path.join(ROOT, "schema"), { recursive: true });
  fs.writeFileSync(path.join(ROOT, "schema", "channel.schema.json"), JSON.stringify({ title: "Channel", ...chSchema }, null, 2) + "\n");

  const schema = z.toJSONSchema(VideoSpec, { io: "input", unrepresentable: "any" });
  const schemaPath = path.join(ROOT, "schema", "video-spec.schema.json");
  fs.mkdirSync(path.dirname(schemaPath), { recursive: true });
  fs.writeFileSync(schemaPath, JSON.stringify({ title: "Video spec", ...schema }, null, 2) + "\n");
  if (!quiet) console.log(`synced ${ids.length} video(s), ${channels.length} channel(s), ${styles.length} style(s)`);
};

if (import.meta.url === `file://${process.argv[1]}`) sync();
